# ══════════════════════════════════ 1. 분수 ══════════════════════════════════

# 1-05 2회차 — 학교에서 집까지 2와 3/11 km, 도서관에서 집까지 9/11 km, 도서관은 그 길 위
def _f105():
    L = 270
    lib = L - L * 9.0 / 25.0            # 25/11 중 9/11 → 도서관 자리 (길이 비율대로)
    y = 40
    f = D.merge(
        D.seg((0, y), (L, y), 'solid', '#6E6A86', 3),
        D.dot((0, y), None, '#3B6FA8'), D.dot((lib, y), None, '#3C8B64'), D.dot((L, y), None, RED),
        D.tag(0, y + 20, '학교', D.INK, 12.5), D.tag(lib, y + 20, '도서관', D.INK, 12.5),
        D.tag(L, y + 20, '집', D.INK, 12.5),
        D.dim_h(0, L, y - 18, '', below=False), D.fr(L / 2, y - 34, '2', '3', '11', ' km', D.SOFT),
        D.dim_h(lib, L, y + 36, ''), D.fr((lib + L) / 2, y + 56, '', '9', '11', ' km', D.SOFT),
        D.dim_h(0, lib, y + 36, ''), D.tag(lib / 2, y + 58, '?', RED, 14, 800),
    )
    return D.svg(f)
FIGS['g105'] = _f105()

