total = 0
for g, rows in SPEC.items():
    km = keymap(g)
    items, pre = [], {}
    for big, small, frm, what, q, a, keys in rows:
        x = km.get((big, small))
        if not x: raise SystemExit('소단원 못 찾음 %s %s-%s' % (g, big, small))
        qid = '%s:qapre%s%s' % (x['key'], big.zfill(2), small)
        items.append({'id': qid, 'big': x['big'], 'small': x['small'], 'kind': 'add',
                      'q': q, 'round': 1, 'ord': 0,
                      'answer': a, 'keys': keys, 'answerBy': 'claude', 'by': 'claude'})
        pre[qid] = {'from': frm, 'what': what}
    total += len(items)

    plan = {'format': 'qr-plan-2', 'grade': g, 'rounds': 3, 'items': items, 'seen': []}
    head = ('\n/* [pre] 2026-09-23 🌱 선수 개념 질문 — 앞 학년·앞 단원에서 배운 것을 확인하는 1회차 질문 (마스터 요청).\n'
            '   소단원 맨 앞(ord 0)에 놓는다. 어른 화면 구분 표시는 review/pre_%s.js 의 window.QR_PRE.\n'
            '   원천 작업도구/질문계단/make_pre.py */\n' % g)
    p = ROOT + r'\review\plan_' + g + '.js'
    s = io.open(p, encoding='utf-8', newline='').read()
    if '\n/* [pre]' in s: s = s[:s.index('\n/* [pre]')]
    s = s.rstrip() + '\n' + head + ("(window.QR_BASE_PLANS = window.QR_BASE_PLANS || []).push({ key:'" + g
        + "_pre_2026-09-23', data:" + json.dumps(plan, ensure_ascii=False, indent=0) + '});\n')
    io.open(p, 'w', encoding='utf-8', newline='').write(s)

    lines = ['/* 🌱 선수 개념 질문 표 — %s (2026-09-23)' % g,
             '   { 질문번호: {from:"배운 곳", what:"무엇"} }',
             '   선생님 학생 기록·학부모 리포트·질문 고르기 화면에서 "이건 앞 학년 내용"임을 표시하는 데 쓴다.',
             '   질문 자체는 plan_%s.js 의 key %s_pre_2026-09-23 블록에 있다. */' % (g, g),
             'window.QR_PRE = window.QR_PRE || {};',
             '(function(m){ for(var k in m) window.QR_PRE[k] = m[k]; })({']
    for i, (qid, v) in enumerate(pre.items()):
        comma = ',' if i < len(pre) - 1 else ''
        lines.append('  %s: { from: %s, what: %s }%s' % (json.dumps(qid, ensure_ascii=False),
                     json.dumps(v['from'], ensure_ascii=False), json.dumps(v['what'], ensure_ascii=False), comma))
    lines.append('});')
    io.open(ROOT + r'\review\pre_' + g + '.js', 'w', encoding='utf-8', newline='').write('\n'.join(lines) + '\n')
    print('%-6s 선수 개념 질문 %d개' % (g, len(items)))

print('합계 %d개' % total)
