def T(x): return x.get('newQ') or x['q']

out = {}
def rec(x):
    if x['id'] not in out:
        out[x['id']] = {k: x[k] for k in ('id', 'big', 'small', 'kind') if k in x}
    return out[x['id']]

log = []
def find(b, s, t):
    x = key3.get((b, s, t))
    if not x: raise SystemExit('못 찾음 %s-%s-%s' % (b, s, t))
    return x

# ── ① 마스터 1단원 결정을 다른 기기에도 (qWas·rWas·offWas 로 보호) ──────────
for m in M['items']:
    if not m['big'].startswith('1.'): continue
    a = byid.get(m['id'])
    if not a: continue
    r, ch = rec(a), False
    if T(m) != T(a):
        r['newQ'] = T(m); r['qWas'] = T(a); ch = True
        log.append(('마스터 문장', T(a), '->', T(m)))
    if m['round'] != a['round'] and not m['off']:
        r['round'] = m['round']; r['rWas'] = a['round']; ch = True
        log.append(('마스터 회차 %s->%s' % (a['round'], m['round']), T(m)))
    if bool(m['off']) != bool(a['off']):
        r['off'] = bool(m['off']); r['offWas'] = bool(a['off']); ch = True
        log.append(('마스터 ' + ('뺌' if m['off'] else '되살림'), T(m)))
    if m.get('ok'): r['ok'] = True; ch = True
    if not ch and not m.get('ok'): out.pop(m['id'], None)

