def numline(a, b, n=10, mark=None, taps=None, hl=(), W=360):
    """a~b 를 n칸으로 나눈 수직선. 양 끝만 수를 적는다. mark=(칸, 글자) · taps={이름: 칸}"""
    f = merge(line((-14, 0), (W + 14, 0), INK, 1.8))
    for k in range(n + 1):
        x = W * k / n; big = k in (0, n)
        f = merge(f, line((x, -8 if big else -5), (x, 8 if big else 5), INK, 1.6 if big else 1.1))
    f = merge(f, tag(0, 26, a, INK, 13), tag(W, 26, b, INK, 13))
    if mark:
        k, s = mark; x = W * k / n
        f = merge(f, D.dot((x, 0), None), tag(x, -16, s, '#B55B45', 14, 800))
    for nm, k in (taps or {}).items():
        x = W * k / n; hot = nm in hl
        g = Fig(); g.add('<circle cx="%.1f" cy="0" r="11" fill="transparent"/>' % x, [(x - 11, -11), (x + 11, 11)])
        g.add('<circle cx="%.1f" cy="0" r="%s" fill="%s"/>' % (x, 6.5 if hot else 4.5, HOT if hot else '#3B6FA8'), [(x, 0)])
        f = merge(f, tapg(nm, g, hot), tag(x, -16, nm, '#8A7BB0', 12.5))
    return f

