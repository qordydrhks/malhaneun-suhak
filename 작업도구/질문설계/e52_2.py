def _sv(w, h, body):
    return ('<svg viewBox="0 0 %d %d" width="%d" style="max-width:100%%;height:auto" xmlns="http://www.w3.org/2000/svg" '
            'font-family="Malgun Gothic,sans-serif">%s</svg>') % (w, h, w, body)
def _tx(x, y, s, c='#2A2350', sz=13, a='middle', w=700):
    return '<text x="%.1f" y="%.1f" font-size="%s" fill="%s" text-anchor="%s" font-weight="%d">%s</text>' % (x, y, sz, c, a, w, s)
def _mixed(x, y, whole, num, den, c='#2A2350'):
    """대분수를 교재 모양으로(자연수 옆에 세운 분수) — (x, y) = 가로선 높이"""
    o = _tx(x - 5, y + 6, whole, c, 15, 'end')
    o += _tx(x + 4, y - 3, num, c, 11) + _tx(x + 4, y + 12, den, c, 11)
    return o + '<line x1="%.1f" y1="%.1f" x2="%.1f" y2="%.1f" stroke="%s" stroke-width="1.1"/>' % (x - 2, y + 1, x + 10, y + 1, c)

def fracline():   # 3회차: 1과 1/6 ~ 3과 2/3 을 5칸으로 · □ = 왼쪽에서 둘째 눈금
    x0, x1, y = 30, 330, 34
    o = '<line x1="%d" y1="%d" x2="%d" y2="%d" stroke="#6E6A86" stroke-width="1.5"/>' % (x0 - 16, y, x1 + 16, y)
    for k in range(6):
        x = x0 + (x1 - x0) * k / 5
        o += '<line x1="%.1f" y1="%d" x2="%.1f" y2="%d" stroke="#6E6A86" stroke-width="1.4"/>' % (x, y - 7, x, y + 7)
    o += _mixed(x0, y + 26, '1', '1', '6') + _mixed(x1, y + 26, '3', '2', '3')
    xq = x0 + (x1 - x0) * 2 / 5
    o += '<rect x="%.1f" y="%d" width="18" height="18" fill="#fff" stroke="#B55B45" stroke-width="1.6"/>' % (xq - 9, y + 14)
    return (_sv(360, 72, o), 300)

def nested_sq():   # 3회차: 한 변 2와 2/3 cm 정사각형 → 각 변의 가운데 점을 이어 계속 · 넷째 정사각형 색칠
    c, h = 110, 92
    pts = [(c - h, c - h), (c + h, c - h), (c + h, c + h), (c - h, c + h)]
    o = ''
    for k in range(4):
        poly = ' '.join('%.1f,%.1f' % p for p in pts)
        fill = '#F6D58E' if k == 3 else ('#E8F1FC' if k == 0 else 'none')
        o += '<polygon points="%s" fill="%s" stroke="#3B6FA8" stroke-width="1.6"/>' % (poly, fill)
        pts = [((pts[i][0] + pts[(i + 1) % 4][0]) / 2, (pts[i][1] + pts[(i + 1) % 4][1]) / 2) for i in range(4)]
    o += '<line x1="%d" y1="%d" x2="%d" y2="%d" stroke="#8A7BB0" stroke-width="1"/>' % (c - h, c + h + 12, c + h, c + h + 12)
    o += _mixed(c - 8, c + h + 30, '2', '2', '3', '#8A7BB0') + _tx(c + 10, c + h + 36, 'cm', '#8A7BB0', 12, 'start', 600)
    return (_sv(230, 250, o), 200)

