#   다시 묻기 핵심에도 같은 말을 붙인다 → apply_alt(help 모듈의 H). 앱 데이터를 만들 때(build_data)도 apply_alt 를 부를 것.
def _alt(k, a): return k if '(=' in k else '%s(= %s)' % (k, a)
