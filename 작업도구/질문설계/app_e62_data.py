def apply_alt(H):
    for t, qs in ALT.items():
        if t not in H: continue
        for i, ks in qs.items():
            ag = H[t][i]['again']
            for j, a in ks.items():
                if j < len(ag['keys']): ag['keys'][j] = _alt(ag['keys'][j], a)
    return H

