def F(x):
    x = Fr(x)
    if x.denominator == 1: return str(x.numerator)
    return format((Decimal(x.numerator) / Decimal(x.denominator)).normalize(), 'f')
def ceil_to(x, u): x, u = Fr(x), Fr(u); q = x / u; return (q.numerator // q.denominator + (0 if q.denominator == 1 else 1)) * u
def floor_to(x, u): x, u = Fr(x), Fr(u); q = x / u; return (q.numerator // q.denominator) * u
def round_to(x, u): x, u = Fr(x), Fr(u); return floor_to(x + u / 2, u)
def cnt(f, lo=0, hi=100000): return sum(1 for n in range(lo, hi + 1) if f(n))
def ns(f, lo=0, hi=100000): return [n for n in range(lo, hi + 1) if f(n)]

