def nl(lo, hi, marks, step=1, lab_every=1, W=380):
    """marks: ('ray', x, filled, 'L'|'R') · ('seg', a, fa, b, fb)"""
    s = W / float(hi - lo); X = lambda v: (Fr(v) - lo) * s; y = 0
    f = Fig(); f = merge(f, seg((-14, y), (W + 14, y), 'solid', '#6E6A86', 1.4))
    v, k = Fr(lo), 0
    while v <= hi:
        x = float(X(v)); f = merge(f, seg((x, y - 5), (x, y + 5), 'solid', '#6E6A86', 1.2))
        if k % lab_every == 0: f = merge(f, tag(x, y + 22, F(v), '#5B4E8C', 12, 600))
        v += Fr(step); k += 1
    col = '#B55B45'
    def dot(x, filled):
        g = Fig(); g.add('<circle cx="%.1f" cy="%.1f" r="5.5" fill="%s" stroke="%s" stroke-width="2"/>' % (x, y - 16, col if filled else '#FFFFFF', col), [(x - 6, y - 22), (x + 6, y - 10)])
        return merge(seg((x, y - 16), (x, y - 4), 'dashed', col, 1), g)
    for m in marks:
        if m[0] == 'ray':
            x = float(X(m[1])); end = -10 if m[3] == 'L' else W + 10
            f = merge(f, seg((x + (-5.5 if m[3] == 'L' else 5.5), y - 16), (end, y - 16), 'solid', col, 2.4), dot(x, m[2]))
        else:
            a, b = float(X(m[1])), float(X(m[3]))
            f = merge(f, seg((a + 5.5, y - 16), (b - 5.5, y - 16), 'solid', col, 2.4), dot(a, m[2]), dot(b, m[4]))
    return f
def cards(items, hl=()):
    f = Fig(); w, h, gap = 64, 40, 12
    for i, t in enumerate(items):
        x = i * (w + gap); hot = t in hl
        g = Fig(); g.add('<rect x="%d" y="0" width="%d" height="%d" rx="8" fill="%s" stroke="%s" stroke-width="%s"/>' % (x, w, h, HOTF if hot else '#FFFFFF', HOT if hot else EDGE, 2.6 if hot else 1.5), [(x, 0), (x + w, h)])
        f = merge(f, tapg(t, merge(g, tag(x + w / 2, h / 2 + 6, t, INK, 16, 700)), hot))
    return f
def tapcards(items, pred):
    ans = [t for t in items if pred(Fr(t))]
    return (lambda hl=(): cards(items, hl)), ans
def tb(rows, cw):
    return lambda: D.table(rows, cw)

