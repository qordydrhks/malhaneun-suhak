LINE = '#374151'; BLUE = '#2f5fb3'; ORG = '#b45309'

def _ln(p, q, col=LINE, w=1.8, dash=''):
    return '<line x1="%.1f" y1="%.1f" x2="%.1f" y2="%.1f" stroke="%s" stroke-width="%s"%s/>' % (p[0], p[1], q[0], q[1], col, w, (' stroke-dasharray="%s"' % dash) if dash else '')

def _ra(p, a1, a2, s=10, col=ORG):   # 직각 표시: 꼭짓점 p, 두 방향 각(도, 수학 방향)
    u = (math.cos(math.radians(a1)), -math.sin(math.radians(a1))); v = (math.cos(math.radians(a2)), -math.sin(math.radians(a2)))
    q1 = (p[0] + u[0] * s, p[1] + u[1] * s); q2 = (p[0] + u[0] * s + v[0] * s, p[1] + u[1] * s + v[1] * s); q3 = (p[0] + v[0] * s, p[1] + v[1] * s)
    return '<polyline points="%.1f,%.1f %.1f,%.1f %.1f,%.1f" fill="none" stroke="%s" stroke-width="1.5"/>' % (q1 + q2 + q3 + (col,))

def _dot(p): return '<circle cx="%.1f" cy="%.1f" r="3" fill="%s"/>' % (p[0], p[1], LINE)

def _lg(title, xl, series, y0, y1, minor, major, wave=False, yu='', xu='', W=270, H=190, x0=0):
    """꺾은선그래프. series = [(값 목록, 색, 이름)] — 값이 None 이면 점을 찍지 않는다(모르는 값)."""
    L, R, T, B = x0 + 46, x0 + W - 14, 30, H - 34
    gap = 14 if wave else 0
    top, bot = T, B - gap
    Y = lambda v: bot - (v - y0) / (y1 - y0) * (bot - top)
    X = lambda i: L + 16 + i * (R - L - 32) / max(1, len(xl) - 1)
    b = _t(x0 + W / 2, 16, title, LINE, 12)
    v = y0
    while v <= y1 + 1e-9:
        maj = abs(v / major - round(v / major)) < 1e-6
        b += _ln((L, Y(v)), (R, Y(v)), '#c7cdd8' if maj else '#e6e9ef', 1 if maj else .8)
        if maj: b += _t(L - 6, Y(v) + 4, ('%g' % v), LINE, 10, 'end')
        v = round(v + minor, 6)
    for i in range(len(xl)): b += _ln((X(i), top), (X(i), B), '#e6e9ef', .8)
    b += _ln((L, top), (L, B), LINE, 1.4) + _ln((L, B), (R, B), LINE, 1.4)
    if wave:
        b += _t(L - 6, B + 4, '0', LINE, 10, 'end')
        z = ' '.join('%.1f,%.1f' % (L + k * (R - L) / 16, B - gap / 2 + (3 if k % 2 else -3)) for k in range(17))
        b += '<polyline points="%s" fill="none" stroke="#9aa3b2" stroke-width="1.3"/>' % z
    for i, s in enumerate(xl): b += _t(X(i), B + 14, s, LINE, 10)
    if yu: b += _t(L - 4, top - 8, '(%s)' % yu, '#5b6270', 9.5, 'end')
    if xu: b += _t(R, B + 28, '(%s)' % xu, '#5b6270', 9.5, 'end')
    for vals, col, name in series:
        pts = [(X(i), Y(val)) for i, val in enumerate(vals) if val is not None]
        idx = [i for i, val in enumerate(vals) if val is not None]
        for k in range(len(pts) - 1):
            if idx[k + 1] == idx[k] + 1: b += _ln(pts[k], pts[k + 1], col, 2)
        b += ''.join('<circle cx="%.1f" cy="%.1f" r="3.2" fill="%s"/>' % (p[0], p[1], col) for p in pts)
    if len(series) > 1:   # 범례
        b += ''.join(_t(L + 4 + 80 * k, H + 4, '— ' + name, col, 10, 'start') for k, (_, col, name) in enumerate(series))
    return b

def _graph(*a, **k): return _svg(k.get('W', 270), k.get('H', 190) + (8 if len(a[2]) > 1 else 0), _lg(*a, **k))

