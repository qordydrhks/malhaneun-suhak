def f_semis(Dm, S=14, parts=None):
    R = Dm * S / 2; parts = parts or [Dm / 2, Dm / 2]; assert sum(parts) == Dm
    d = 'M0,0 A%.1f,%.1f 0 0 1 %.1f,0' % (R, R, 2 * R); x = 2 * R
    for pd in reversed(parts):
        r = pd * S / 2; d += ' A%.1f,%.1f 0 0 0 %.1f,0' % (r, r, x - 2 * r); x -= 2 * r
