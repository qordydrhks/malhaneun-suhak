def gridcount(rad):
    """반지름 rad(정수) 원 — 원 안에 완전히 든 칸 · 원에 걸치거나 든 칸"""
    import math
    ins = out = 0
    for i in range(-rad, rad):
        for j in range(-rad, rad):
            cs = [(i, j), (i + 1, j), (i, j + 1), (i + 1, j + 1)]
            dmax = max(x * x + y * y for x, y in cs)
            nx, ny = min(max(0, i), i + 1) if not (i <= 0 <= i + 1) else 0, min(max(0, j), j + 1) if not (j <= 0 <= j + 1) else 0
            nx = 0 if i <= 0 <= i + 1 else (i if i > 0 else i + 1); ny = 0 if j <= 0 <= j + 1 else (j if j > 0 else j + 1)
            dmin = nx * nx + ny * ny
            if dmax <= rad * rad: ins += 1
            if dmin < rad * rad: out += 1
    return ins, out

