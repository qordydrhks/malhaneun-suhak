def nv(s):
    s = str(s).replace('−', '-')
    if re.fullmatch(r'-?\d+', s): return Fr(int(s))
    m_ = re.fullmatch(r'(-?)\{(\d+)\|(\d+)\}', s)
    if m_: return Fr(int(m_.group(2)), int(m_.group(3))) * (-1 if m_.group(1) else 1)
    return None

