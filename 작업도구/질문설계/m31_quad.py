def sgn_ok(A, B, C, quad):
    """그래프가 그 사분면을 지나는지(표본 x로)"""
    import itertools
    xs = [i / 20 for i in range(-400, 401)]
    for X in xs:
        Y = A * X * X + B * X + C
        if (quad == 1 and X > 0 and Y > 0) or (quad == 2 and X < 0 and Y > 0) or (quad == 3 and X < 0 and Y < 0) or (quad == 4 and X > 0 and Y < 0): return True
    return False
import itertools as _it
def never(sa, sb, sc):
    """부호가 (sa, sb, sc)인 모든 경우에 항상 지나지 않는 사분면"""
    res = {1, 2, 3, 4}
    for A, B, C in _it.product([0.3, 1, 3], [0.5, 2, 6], [0.2, 1, 8]):
        res = {qd for qd in res if not sgn_ok(sa * A, sb * B, sc * C, qd)}
    return res
