FIGLOG = {}
def used(owner, A, B, C):
    key = (Fr(A).limit_denominator(100), Fr(B).limit_denominator(100), Fr(C).limit_denominator(100))
    FIGLOG.setdefault(key, set()).add(owner)

def G(owner, xr, yr, w=200, sy=None):
    g = Graph(xr, yr, w=w, sy=sy)
    _curve = g.curve
    def curve(A, B, C, **kw):
        used(owner, A, B, C); return _curve(A, B, C, **kw)
    g.curve = curve
    return g

def card(owner, A, P, Q, xr, yr, w=118, sy=None, yint=True, ticks=True, col=CURVE, tap=None):
    """그래프 카드(작게) — 꼭짓점 눈금·점선, y절편 숫자"""
    g = G(owner, xr, yr, w=w, sy=sy); g.o = False          # 카드는 원점 O 를 적지 않는다(눈금 숫자와 겹침)
    B_, C_ = -2 * A * P, A * P * P + Q
    g.curve(A, B_, C_, col=col, w=1.8)
    if ticks:
        g.guide(P, Q); g.pt(P, Q, r=2.6)
        if P: g.xt(P)
        if Q: g.yt(Q, right=P < 0)
        if yint and C_ != Q: g.pt(0, C_, r=2.6); g.yt(C_, right=P < 0)
    return g.svg(tap and {tap}, width=150)

