def fs(x, u=''):
    x = Fr(x)
    if x.denominator == 1: s = str(x.numerator)
    elif x < 1: s = '%d/%d' % (x.numerator, x.denominator)
    else: w = x.numerator // x.denominator; s = mx(w, x.numerator - w * x.denominator, x.denominator)
    return s + u
def q(code, r, lv, stem, ans, wr, ex, u='', src=''):
    U.mc(code, r, lv, stem, fs(ans, u), [(w if isinstance(w, str) else fs(w, u), n) for w, n in wr], ex, val=Fr(ans), src=src)
def n_(code, r, lv, stem, ans, wr, ex, u='', src=''):
    """답이 개수·자연수(단위 붙음)"""
    U.mc(code, r, lv, stem, '%s%s' % (ans, u), [(('%s%s' % (w, u)) if not isinstance(w, str) else w, n) for w, n in wr], ex, val=ans, src=src)
def t_(code, r, lv, stem, ans, wr, ex, src=''):
    """답이 글(값으로 검산하지 않음)"""
    U.mc(code, r, lv, stem, ans, wr, ex, src=src)
def M_(w, n, d): return Fr(w) + Fr(n, d)
