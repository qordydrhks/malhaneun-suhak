def cube_num(top, front, right, origin=(0, 0)):
    f = D.box(2, 2, 2, origin=origin); g = D.box_pts(2, 2, 2, origin)
    FTL, FTR, BTR, BTL, FBL, FBR, BBR, BBL = g
    cen = lambda ps: (sum(p[0] for p in ps) / 4, sum(p[1] for p in ps) / 4)
    for ps, t in (([FTL, FTR, FBR, FBL], front), ([FTR, BTR, BBR, FBR], right), ([FTL, FTR, BTR, BTL], top)):
        x, y = cen(ps); f = merge(f, tag(x, y + 6, str(t), INK, 15))
    return f
def nets(cells, labels, colw=34):
    n = max(c_[0] for c_ in cells) + 1; m = max(c_[1] for c_ in cells) + 1
    return lambda: D.net(cells, [colw] * n, [colw] * m, labels={k: v for k, v in labels.items()})
def net_dims(cells, cw, rh, k=10):
    def fig():
        f = D.net(cells, [x * k for x in cw], [y * k for y in rh])
        X = [0]
        for w in cw: X.append(X[-1] + w * k)
        Y = [0]
        for h in rh: Y.append(Y[-1] + h * k)
        done = set()
        for (cc, r) in sorted(cells, key=lambda t: (-t[1], t[0])):
            if ('c', cc) not in done:
                f = merge(f, tag((X[cc] + X[cc + 1]) / 2, max(Y[rr + 1] for (c2, rr) in cells if c2 == cc) + 15, '%g cm' % cw[cc], '#5B4E8C', 11)); done.add(('c', cc))
        seen = set()
        for r in range(len(rh)):
            if rh[r] in seen: continue
            seen.add(rh[r]); cr = max(c2 for (c2, rr) in cells if rr == r)
            f = merge(f, tag(X[cr + 1] + 5, (Y[r] + Y[r + 1]) / 2 + 4, '%g cm' % rh[r], '#5B4E8C', 11, 700, 'start'))
        return f
    return fig
def per_net(cells, colw, rowh):
    have = set(cells); s = 0
    for (cc, r) in cells:
        for nb, ln in (((cc, r - 1), colw[cc]), ((cc, r + 1), colw[cc]), ((cc - 1, r), rowh[r]), ((cc + 1, r), rowh[r])):
            if nb not in have: s += ln
    return s

