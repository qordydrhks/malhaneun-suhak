SF, SE = D.SHADE

def _hex():   # 지름 2 cm 원 · 원 안 정육각형(꼭짓점이 옆으로) · 원 밖 정사각형 — 둘레 수치는 적지 않음(= 답)
    r = 56
    hexa = [(r * math.cos(math.radians(60 * i)), r * math.sin(math.radians(60 * i))) for i in range(6)]
    f = D.merge(D.poly([(-r, -r), (r, -r), (r, r), (-r, r)], 'amber', fill=False), D.circle((0, 0), r, 'blue'),
                D.poly(hexa, 'green', fill=False), D.dim_h(-r, r, r + 14, '2 cm'))
    return (D.svg(f), 190)

def _sq():    # 반지름 6 cm 원 · 원 안 정사각형(꼭짓점이 원 위) · 원 밖 정사각형
    r = 56
    f = D.merge(D.poly([(-r, -r), (r, -r), (r, r), (-r, r)], 'rose', fill=False), D.circle((0, 0), r, 'blue'),
                D.poly([(0, -r), (r, 0), (0, r), (-r, 0)], 'green', fill=False),
                D.seg((0, 0), (r * 0.7071, -r * 0.7071), 'solid', '#6E6A86', 1.3), D.dot((0, 0)), D.tag(r * 0.42, -r * 0.18, '6 cm', D.INK, 12))
    return (D.svg(f), 190)

def _band():  # 지름 10 cm 둥근 통 2개를 끈으로 한 바퀴 — 끈은 굵은 선
    r = 40
    f = D.merge(D.circle((0, 0), r, 'blue'), D.circle((2 * r, 0), r, 'blue'))
    f = D.merge(f, D.path('M 0 %d L %d %d A %d %d 0 0 1 %d %d L 0 %d A %d %d 0 0 1 0 %d Z' % (-r, 2 * r, -r, r, r, 2 * r, r, r, r, r, -r),
                          [(-r - 3, -r - 3), (3 * r + 3, r + 3)], fill='none', stroke='#A97C22', sw=3.2))
    f = D.merge(f, D.seg((-r, 0), (r, 0), 'dashed', '#6E6A86', 1.2), D.tag(0, -7, '10 cm', D.INK, 12), D.tag(r, r + 24, '끈', '#A97C22', 12))
    return (D.svg(f), 210)

def _sqc():   # 한 변 10 cm 정사각형 안에 꼭 맞는 원 — 색칠한 부분은 정사각형에서 원을 뺀 부분
    a = 120; r = a / 2
    d = 'M 0 0 H %d V %d H 0 Z M %d %d A %d %d 0 1 0 %d %d A %d %d 0 1 0 %d %d Z' % (a, a, a / 2 - r, a / 2, r, r, a / 2 + r, a / 2, r, r, a / 2 - r, a / 2)
    f = D.merge(D.path(d, [(0, 0), (a, a)], fill=SF, stroke=SE, sw=1.5, evenodd=True), D.dim_h(0, a, a + 12, '10 cm'))
    return (D.svg(f), 170)

def _move():  # 가로 6 cm·세로 4 cm 직사각형 — 위는 반원만큼 파이고 아래는 같은 반원이 붙음
    s = 18; w, h = 6 * s, 4 * s; r = w / 2
    d = 'M 0 0 A %g %g 0 0 0 %g 0 L %g %g A %g %g 0 0 1 0 %g Z' % (r, r, w, w, h, r, r, h)
    f = D.merge(D.path(d, [(0, 0), (w, h + r)], fill=SF, stroke=SE, sw=1.5),
                D.seg((0, 0), (w, 0), 'dashed', '#6E6A86', 1.1), D.seg((0, h), (w, h), 'dashed', '#6E6A86', 1.1),
                D.dim_h(0, w, -12, '6 cm', below=False), D.dim_v(0, h, -12, '4 cm'))
    return (D.svg(f), 170)

