def rep(path, pairs):
    t = io.open(path, encoding='utf-8').read()
    for a, b in pairs:
        n = t.count(a)
        assert n == 1, (os.path.basename(path), n, a[:80])
        t = t.replace(a, b)
    io.open(path, 'w', encoding='utf-8', newline='').write(t)
    print('ok', os.path.basename(path), len(pairs))

