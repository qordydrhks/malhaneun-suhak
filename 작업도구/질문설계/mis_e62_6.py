def g_semi(r_, s=14):
    R = r_ * s; d = 'M%.1f,0 A%.1f,%.1f 0 0 0 %.1f,0 Z' % (-R, R, R, R)
    f = merge(D.path(d, [(-R, 0), (R, R)], fill='#E6F4EC', stroke='#3C8B64'), D.seg((0, 0), (R, 0), color='#6E6A86'), D.dot((0, 0)))
    return merge(f, tag(R / 2, -6, '%s cm' % r_, D.INK, 12), D.spin((-R, 0), (R, 0), '지름을 기준으로 한 바퀴'))
def g_badnet(rr=18, H=70):
    W = 2 * 3.14 * rr
    f = merge(D.poly([(0, 0), (W, 0), (W, H), (0, H)], 'blue'), D.circle((W * 0.25, H + rr), rr, 'amber'), D.circle((W * 0.75, H + rr), rr, 'amber'))
    return merge(f, tag(W / 2, -10, '친구가 그린 전개도', D.SOFT, 12, 600))
def g_cyl(r_, h_, s=9, lab=True):
    r, h = r_ * s, h_ * s
    f = D.cyl(r, h, 0, 0)
    if lab: f = merge(f, D.seg((0, h), (r, h), color='#6E6A86'), tag(r / 2, h - 6, '%s cm' % r_, D.INK, 12), D.dim_v(0, h, r + 14, '%s cm' % h_, left=False))
    return f
def g_cylsphere(h_, s=8):
    r = h_ * s / 2; f = merge(D.cyl(r, 2 * r, 0, 0, 'blue'), D.sphere(r, (0, r), 'green'))
    return merge(f, D.dim_v(0, 2 * r, r + 16, '%s cm' % h_, left=False))
def g_cone(r_, l_, s=8):
    import math
    r = r_ * s; h = math.sqrt(l_ * l_ - r_ * r_) * s
    f = merge(D.cone(r, h, 0, 0), D.seg((0, h), (r, h), color='#6E6A86'))
    return merge(f, tag(r / 2, h - 6, '%s cm' % r_, D.INK, 12), tag(r / 2 + 22, h / 2, '%s cm' % l_, D.INK, 12))
def g_cubesphere(a_, s=10):
    A = a_ * s
    f = merge(D.poly([(0, 0), (A, 0), (A, A), (0, A)], 'blue', fill=False), D.circle((A / 2, A / 2), A / 2, 'green'))
    return merge(f, D.dim_h(0, A, A + 12, '%s cm' % a_), tag(A / 2, -10, '앞에서 본 모양', D.SOFT, 12, 600))

