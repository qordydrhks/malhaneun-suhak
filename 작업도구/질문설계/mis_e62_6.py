def g_rect(w_, h_, axis='세로', s=12):
    w, h = w_ * s, h_ * s
    f = merge(D.poly([(0, 0), (w, 0), (w, h), (0, h)], 'blue'), D.dim_h(0, w, h + 12, '%s cm' % w_), D.dim_v(0, h, w + 14, '%s cm' % h_, left=False))
    return merge(f, D.spin((0, 0), (0, h), '%s를 기준으로 한 바퀴' % axis) if axis == '세로' else D.spin((0, h), (w, h), '%s를 기준으로 한 바퀴' % axis))
def g_tri(b_, h_, s=9, axis='높이'):
    w, h = b_ * s, h_ * s
    f = merge(D.poly([(0, 0), (0, h), (w, h)], 'green'), D.right_angle((0, h), (0, 0), (w, h)), D.dim_h(0, w, h + 12, '%s cm' % b_), D.dim_v(0, h, -12, '%s cm' % h_))
