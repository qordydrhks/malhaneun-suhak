def iso(base, apex_deg, o=(0, 0)):
    """밑변 base(cm) · 꼭지각 apex_deg 인 이등변삼각형 — 꼭짓점 ㄱ(위)·ㄴ(왼)·ㄷ(오른)"""
    h = base / 2 / math.tan(math.radians(apex_deg / 2))
    return (o[0] + base / 2, o[1] + h), o, (o[0] + base, o[1])
def tri_grid(n, s):
    """한 변이 n칸인 정삼각형을 작은 정삼각형으로 나눈 그림(한 칸 s cm)"""
    h = s * math.sqrt(3) / 2
    f = tri((n * s / 2, n * h), (0, 0), (n * s, 0))
    for k in range(1, n):
        y = k * h
        f = merge(f, L((k * s / 2, y), (n * s - k * s / 2, y), EDGE, 1.3))                 # 가로
        f = merge(f, L((k * s, 0), (k * s / 2 + n * s / 2, (n - k) * h), EDGE, 1.3))         # 오른쪽 위로
        f = merge(f, L((k * s, 0), (k * s / 2, k * h), EDGE, 1.3))                           # 왼쪽 위로
    return f
def count_eq(n):
    up = sum((n - k + 1) * (n - k + 2) // 2 for k in range(1, n + 1))
    dn = sum((n - 2 * k + 1) * (n - 2 * k + 2) // 2 for k in range(1, n // 2 + 1))
    return up + dn

