def M(p): return (p[0] * CM, -p[1] * CM)
def P(a, r, o=(0, 0)): return (o[0] + r * math.cos(math.radians(a)), o[1] + r * math.sin(math.radians(a)))
def deg(o, p, q): return angle_at(o, p, q)
def tri(A, Bp, C, color=EDGE, fill=FILL): return shape([M(A), M(Bp), M(C)], color, fill)
