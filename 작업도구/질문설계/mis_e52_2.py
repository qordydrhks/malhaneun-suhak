def fs(x, u=''):
    x = Fr(x)
    if x.denominator == 1: s = str(x.numerator)
    elif x < 1: s = '%d/%d' % (x.numerator, x.denominator)
    else: w = x.numerator // x.denominator; s = mx(w, x.numerator - w * x.denominator, x.denominator)
    return s + u
def q(code, r, lv, stem, ans, wr, ex, u='', src='', fig=None):
    U.mc(code, r, lv, stem, fs(ans, u), [(w if isinstance(w, str) else fs(w, u), n) for w, n in wr], ex, val=Fr(ans), fig=fig, src=src)
def M_(w, n, d): return Fr(w) + Fr(n, d)
def nlbox(a, b, parts, at):
    """a ~ b 를 parts 칸으로 똑같이 나눈 수직선, at 번째 눈금에 □"""
    W = 360; f = Fig(); f = merge(f, seg((-14, 0), (W + 14, 0), 'solid', '#6E6A86', 1.4))
    for k in range(parts + 1):
        x = W * k / parts; f = merge(f, seg((x, -6), (x, 6), 'solid', '#6E6A86', 1.4))
    for x, v in ((0, a), (W, b)):
        w = v.numerator // v.denominator; n = v.numerator - w * v.denominator
        f = merge(f, D.fr(x, 28, str(w), str(n), str(v.denominator), size=13))
    x = W * at / parts
    f.add('<rect x="%.1f" y="-34" width="22" height="22" fill="#FFFFFF" stroke="#B55B45" stroke-width="1.8"/>' % (x - 11), [(x - 11, -34), (x + 11, -12)])
    return merge(f, seg((x, -12), (x, -6), 'solid', '#B55B45', 1.4))

