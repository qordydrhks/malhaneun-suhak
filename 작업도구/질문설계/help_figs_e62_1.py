def NLINE(x, y, w, n, labels, sz=11):
    """0~1 수직선(n칸) — labels: {칸 번호: (분자, 분모) 또는 글자}"""
    o = L((x, y), (x + w, y), EDGE, 1.4)
    for k in range(n + 1):
        xx = x + w * k / n; o += L((xx, y - 5), (xx, y + 5), EDGE, 1.2)
        lb = labels.get(k)
        if isinstance(lb, tuple): o += FR(xx, y + 24, lb[0], lb[1], LINE, sz)[0]
        elif lb is not None: o += T(xx, y + 22, lb, LINE, sz + 1)
    return o

def HOPS(x, y, w, n, k, step, c=ORG, lab=True):
    """수직선 위에 step 칸씩 k번 뛰는 굽은 화살표"""
    o = ''
    for j in range(k):
        a = x + w * (j * step) / n; b = x + w * ((j + 1) * step) / n
        o += CURVE((a, y), (b, y), c, True, 18)
        if lab: o += T((a + b) / 2, y - 24, '%d' % (j + 1), c, 11, 'middle', 700)
    return o

