TR = [lambda x, y: (x, y), lambda x, y: (-y, x), lambda x, y: (-x, -y), lambda x, y: (y, -x),
      lambda x, y: (-x, y), lambda x, y: (y, x), lambda x, y: (x, -y), lambda x, y: (-y, -x)]
def norm(pts):
    mx_, my = min(p[0] for p in pts), min(p[1] for p in pts); return frozenset((p[0] - mx_, p[1] - my) for p in pts)
def congruent(a, b): return any(norm([t(*p) for p in a]) == norm(b) for t in TR)
def cen(pts): return (sum(p[0] for p in pts) / len(pts), sum(p[1] for p in pts) / len(pts))
def keyset(pts): return frozenset((round(p[0], 6), round(p[1], 6)) for p in pts)
def line_sym(pts):
    """대칭축 개수(꼭짓점 집합이 제자리로 오는 축). 축 후보 = 무게중심을 지나는 꼭짓점·변의 가운데 방향"""
    o = cen(pts); cand = set()
    for p in pts + [((pts[i][0] + pts[i - 1][0]) / 2, (pts[i][1] + pts[i - 1][1]) / 2) for i in range(len(pts))]:
        if math.hypot(p[0] - o[0], p[1] - o[1]) > 1e-9:
            cand.add(round(math.degrees(math.atan2(p[1] - o[1], p[0] - o[0])) % 180, 4) % 180)
    n = 0
    for a in cand:
        b = (o[0] + math.cos(math.radians(a)), o[1] + math.sin(math.radians(a)))
        if keyset([refl(p, o, b) for p in pts]) == keyset(pts): n += 1
    return n
def point_sym(pts):
    o = cen(pts); return keyset([rot(p, o, 180) for p in pts]) == keyset(pts)

