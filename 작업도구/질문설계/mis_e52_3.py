def rot(p, o, deg):
    a = math.radians(deg); x, y = p[0] - o[0], p[1] - o[1]
    return (o[0] + x * math.cos(a) - y * math.sin(a), o[1] + x * math.sin(a) + y * math.cos(a))
def refl(p, a, b):
    f = foot(p, a, b); return (2 * f[0] - p[0], 2 * f[1] - p[1])
def ang(o, p, q): return angle_at(o, p, q)
