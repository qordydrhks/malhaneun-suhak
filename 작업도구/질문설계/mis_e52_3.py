def strip(n, s):
    pts = []
    for i in range(n):
        if i % 2 == 0: pts.append([(i / 2 * s, 0), (i / 2 * s + s, 0), (i / 2 * s + s / 2, s * math.sqrt(3) / 2)])
        else: pts.append([((i + 1) / 2 * s, 0), ((i + 1) / 2 * s - s / 2, s * math.sqrt(3) / 2), ((i + 1) / 2 * s + s / 2, s * math.sqrt(3) / 2)])
    return pts
