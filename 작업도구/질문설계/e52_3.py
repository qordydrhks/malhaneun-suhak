import draw as D
S = 18

def _mid(p, q, text, off=(0, 0)):
    return D.tag((p[0] + q[0]) / 2 + off[0], (p[1] + q[1]) / 2 + off[1], text, D.SOFT, 12)

def _tri():   # 합동인 두 삼각형: ㄱㄴ 6 · ㄴㄷ 7 · ㄱㄷ 5 cm, 오른쪽은 180° 돌린 모양
    x = (36 - 25 + 49) / 14.0; y = math.sqrt(36 - x * x)
    A, B, C = (x * S, -y * S), (0, 0), (7 * S, 0)
    f = D.merge(D.poly([A, B, C], 'blue'), D.dot(A, 'ㄱ'), D.dot(B, 'ㄴ', at='left'), D.dot(C, 'ㄷ', at='right'),
                _mid(A, B, '6 cm', (-22, 0)), _mid(B, C, '7 cm', (0, 16)), _mid(A, C, '5 cm', (22, 0)))
    ox, oy = 7 * S + 60 + 7 * S, -y * S          # 180° 돌림: (px, py) → (ox - px, oy - py)
    R = lambda p: (ox - p[0], oy - p[1])
    A2, B2, C2 = R(A), R(B), R(C)
    f = D.merge(f, D.poly([A2, B2, C2], 'amber'), D.dot(A2, 'ㄹ', at='below'), D.dot(B2, 'ㅁ', at='right'), D.dot(C2, 'ㅂ', at='left'))
    return (D.svg(f), 330)

def _sym():   # 선대칭도형(오각형) · 대칭축 ㄱㅂ · 선분 ㄴㅁ이 축과 만나는 점 ㅅ · 변 ㄴㄷ 4 cm
    T, N, Dd, R, M = (0, -3.6 * S), (3.0 * S, -1.2 * S), (2.2 * S, 2.6 * S), (-2.2 * S, 2.6 * S), (-3.0 * S, -1.2 * S)
    dist = math.hypot(N[0] - Dd[0], N[1] - Dd[1]) / S
    f = D.merge(D.poly([T, N, Dd, R, M], 'green'), D.seg((0, -4.6 * S), (0, 3.4 * S), 'dashed', '#B55B45', 1.4),
                D.seg(N, M, 'dashed', '#6E6A86', 1.1),
                D.dot(T, 'ㄱ', at='right'), D.dot(N, 'ㄴ', at='right'), D.dot(Dd, 'ㄷ', at='right'), D.dot(R, 'ㄹ', at='left'),
                D.dot(M, 'ㅁ', at='left'), D.dot((0, 2.6 * S), 'ㅂ', at='below'), D.dot((0, -1.2 * S), 'ㅅ', at='above'),
                _mid(N, Dd, '%d cm' % round(dist), (24, 0)))
    return (D.svg(f), 220)

def _half():  # 선대칭도형의 반쪽(대칭축 오른쪽) — 3 · 2 · 4 · 2 cm, 대칭축 위 선분 5 cm(둘레가 아님 — 마스터 10/16 이 길이도 적어야 애매하지 않다)
    A, B, Dp, E = (0, 0), (60, 0), (40, 100), (0, 100)          # 1 cm = 20 px
    dx, dy = Dp[0] - B[0], Dp[1] - B[1]; d = math.hypot(dx, dy)   # 점 C: BC = 2 cm, CD = 4 cm
    a = (40 ** 2 - 80 ** 2 + d * d) / (2 * d); h = math.sqrt(40 ** 2 - a * a)
    bx, by = B[0] + a * dx / d, B[1] + a * dy / d
    C = (bx + h * dy / d, by - h * dx / d)
    if C[0] < bx: C = (bx - h * dy / d, by + h * dx / d)
    Dy = Dp[1]
    f = D.merge(D.poly([A, B, C, Dp, E], 'blue'), D.seg((0, -16), (0, Dy + 16), 'dashed', '#B55B45', 1.4),
                _mid(A, B, '3 cm', (0, -10)), _mid(B, C, '2 cm', (20, -4)), _mid(C, Dp, '4 cm', (24, 4)), _mid(Dp, E, '2 cm', (0, 16)),
                D.tag(-8, Dy / 2 - 6, '대칭축', '#B55B45', 11.5, 600, 'end'), D.tag(-8, Dy / 2 + 12, '5 cm', D.SOFT, 12, 400, 'end'))
    return (D.svg(f), 200)

def _pt():    # 점대칭도형(육각형) · 대칭의 중심 ㅇ · ㄱㄴ 5 · ㄴㄷ 3 · ㄷㄹ 4 cm
    s = 16
    P1, P2 = (-60.0, -30.0), (20.0, -30.0)
    c1, r1, c2, r2 = P2, 3 * s, (-P1[0], -P1[1]), 4 * s
    dx, dy = c2[0] - c1[0], c2[1] - c1[1]; d = math.hypot(dx, dy)
    a = (r1 * r1 - r2 * r2 + d * d) / (2 * d); h = math.sqrt(r1 * r1 - a * a)
    bx, by = c1[0] + a * dx / d, c1[1] + a * dy / d
    P3 = (bx + h * dy / d, by - h * dx / d)
    pts = [P1, P2, P3, (-P1[0], -P1[1]), (-P2[0], -P2[1]), (-P3[0], -P3[1])]
    names = ['ㄱ', 'ㄴ', 'ㄷ', 'ㄹ', 'ㅁ', 'ㅂ']; ats = ['above', 'above', 'right', 'below', 'below', 'left']
    f = D.poly(pts, 'rose')
    for p, nm, at in zip(pts, names, ats): f = D.merge(f, D.dot(p, nm, at=at))
    f = D.merge(f, D.dot((0, 0), 'ㅇ', '#B55B45', at='below'),
                _mid(pts[0], pts[1], '5 cm', (0, -14)), _mid(pts[1], pts[2], '3 cm', (6, -12)), _mid(pts[2], pts[3], '4 cm', (24, 0)))
    return (D.svg(f), 230)

