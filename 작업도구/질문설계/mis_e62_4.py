F = Fr
def fs(x, u=''):
    x = Fr(x)
    if x.denominator == 1: s = str(x.numerator)
    elif x < 1: s = '%d/%d' % (x.numerator, x.denominator)
    else: w = x.numerator // x.denominator; s = mx(w, x.numerator - w * x.denominator, x.denominator)
    return s + u
def rt(a, b): return '%s : %s' % (a, b)
def ratio(s):
    a, b = s.split(' : '); return Fr(a) / Fr(b)
def simp(a, b):
    a, b = Fr(a), Fr(b); k = Fr(a.denominator * b.denominator)
    x, y = int(a * k), int(b * k); g = gcd(x, y); return x // g, y // g
def R(code, r, lv, stem, ans, wr, ex, src='', same=None, fig=None):
    """답이 비 — same=True 면 답과 비율이 같은 오답이 없는지, 가장 간단한지 본다"""
    if same is not None:
        for w, _ in wr:
            if ' : ' in w and w.count(':') == 1:
                try: assert ratio(w) != ratio(ans), ('오답이 답과 비율이 같음', stem, w)
                except ZeroDivisionError: pass
    U.mc(code, r, lv, stem, ans, wr, ex, src=src, fig=fig)
def N(code, r, lv, stem, ans, wr, ex, u='', src='', fig=None):
    ans = Fr(ans)
    U.mc(code, r, lv, stem, fs(ans, u), [(w if isinstance(w, str) else fs(w, u), n) for w, n in wr], ex, val=ans, src=src, fig=fig)
def T(code, r, lv, stem, ans, wr, ex, src=''):
    U.mc(code, r, lv, stem, ans, wr, ex, src=src)
def isprop(s):
    l, r = s.split(' = '); return ratio(l) == ratio(r)

