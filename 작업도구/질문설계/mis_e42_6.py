def f62b():
    h = reg(6, 2, 90); f = poly_(h)
    for k in range(6):
        a, b = h[k], h[(k + 1) % 6]; m = ((a[0] + b[0]) / 2, (a[1] + b[1]) / 2)
        ln = math.hypot(m[0], m[1]); t = (m[0] / ln * 2 * math.sqrt(3) / 2 + m[0], m[1] / ln * 2 * math.sqrt(3) / 2 + m[1])
