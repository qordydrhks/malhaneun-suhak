def X(s): return Dd(str(s))
def ds(x):
    x = X(x)
    s = format(x.normalize(), 'f')
    return s
def q(code, r, lv, stem, ans, wr, ex, u='', src=''):
    """답과 오답이 수(Decimal·int·str 수) — 단위 u 를 붙인다. 글로 된 오답은 그대로"""
    def f(w): return w if (isinstance(w, str) and not _isnum(w)) else ds(w) + u
    U.mc(code, r, lv, stem, ds(ans) + u, [(f(w), n) for w, n in wr], ex, val=Fr(ds(ans)), src=src)
def _isnum(s):
    try: X(s); return True
    except Exception: return False
def t_(code, r, lv, stem, ans, wr, ex, src=''):
    U.mc(code, r, lv, stem, ans, wr, ex, src=src)
def rnd(x, places):
    return X(x).quantize(Dd(1).scaleb(-places), rounding=ROUND_HALF_UP)
def dv(a, b):
    v = X(a) / X(b); assert v == v.quantize(Dd('0.000001')), (a, b, v)
    return v.normalize()

