def numline(lo, hi, a, a_open, b, b_open):
    """수직선 — lo~hi 눈금, a~b 굵은 선, 끝점 ●(포함) / ○(포함 안 함). 범위 이름은 적지 않음(= 답)"""
    s = 30; f = D.seg((-12, 0), ((hi - lo) * s + 12, 0), 'solid', '#6E6A86', 1.4)
    for v in range(lo, hi + 1):
        x = (v - lo) * s
        f = D.merge(f, D.seg((x, -5), (x, 5), 'solid', '#6E6A86', 1.1), D.tag(x, 22, str(v), D.INK, 12))
    xa, xb = (a - lo) * s, (b - lo) * s
    f = D.merge(f, D.seg((xa, 0), (xb, 0), 'solid', '#B55B45', 3.4))
    for x, op in ((xa, a_open), (xb, b_open)):
        f = D.merge(f, D.circle((x, 0), 5.5, '#FFFFFF' if op else '#B55B45', fill=True, sw=1.8))
    return (D.svg(f), 300)

