def spin(parts, origin=(0, 0), r=34, label=None):
    """parts: 칸마다 색(같은 크기). 'y' 노랑 · 'b' 파랑 · 'g' 초록"""
    col = {'y': '#F6D58E', 'b': '#A9C8EC', 'g': '#AEDAC3'}
    f = Fig(); ox, oy = origin; n = len(parts)
    for i, p in enumerate(parts):
        a0, a1 = 2 * math.pi * i / n - math.pi / 2, 2 * math.pi * (i + 1) / n - math.pi / 2
        x0, y0, x1, y1 = ox + r * math.cos(a0), oy + r * math.sin(a0), ox + r * math.cos(a1), oy + r * math.sin(a1)
        if n == 1:
            f.add('<circle cx="%.1f" cy="%.1f" r="%d" fill="%s" stroke="%s" stroke-width="1.4"/>' % (ox, oy, r, col[p], EDGE), [(ox - r, oy - r), (ox + r, oy + r)])
        else:
            f.add('<path d="M%.1f,%.1f L%.1f,%.1f A%d,%d 0 0 1 %.1f,%.1f Z" fill="%s" stroke="%s" stroke-width="1.2"/>' % (ox, oy, x0, y0, r, r, x1, y1, col[p], EDGE), [(ox - r, oy - r), (ox + r, oy + r)])
    if label: f = merge(f, tag(ox, oy + r + 18, label, INK, 13))
    return f
def yel(parts): return Fr(parts.count('y'), len(parts))

